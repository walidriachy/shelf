const { contextBridge, ipcRenderer } = require('electron');

const call = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('shelf', {
  init: call('init'),
  add: call('add'),
  update: call('update'),
  remove: call('remove'),
  reprocess: call('reprocess'),
  reprocessAll: call('reprocess-all'),
  detail: call('detail'),
  openFile: call('open-file'),
  openCopy: call('open-copy'),
  showFolder: call('show-folder'),
  signin: call('signin'),
  ask: call('ask'),
  open: call('open'),
  addCategory: call('add-category'),
  removeCategory: call('remove-category'),
  settings: call('settings'),
  syncNow: call('sync-now'),
  r2Test: call('r2-test'),
  r2OpenToken: call('r2-open-token'),
  r2Connect: call('r2-connect'),
  r2Disconnect: call('r2-disconnect'),
  onR2Step: (fn) => ipcRenderer.on('r2-step', (_, m) => fn(m)),
  library: call('library'),
  pickFolder: call('pick-folder'),
  setLibrary: call('set-library'),
  showLibrary: call('show-library'),
  copy: call('copy'),
  connect: call('connect'),
  exportPage: call('export-page'),
  sharePage: call('share-page'),
  unsharePage: call('unshare-page'),
  disconnect: call('disconnect'),
  exportAll: call('export'),
  onState: (fn) => ipcRenderer.on('state', (_, s) => fn(s)),
  onSync: (fn) => ipcRenderer.on('sync', (_, s) => fn(s)),
});
